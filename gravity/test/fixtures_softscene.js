/**
 * A teardrop: a disc of radius R with a tangent wedge running out to an apex.
 *
 * The construction lives here rather than inline in a test because two reasonable teardrop
 * constructions disagree about WHICH ring separation comes out closest, so any test asserting
 * a separation has to pin the shape exactly. Half-angle satisfies sin(alpha) = R / D, so the
 * tip angle is 2 * alpha. Sharper tips move the convergence band outward as 1 / sin(alpha),
 * which is the whole reason the brace rule cannot use a ring-separation threshold.
 */
function teardrop(tipDegrees, R, segments) {
  var alpha = tipDegrees / 2 * Math.PI / 180;
  var D = R / Math.sin(alpha);
  var ta = Math.acos(R / D);
  var ring = [];
  for (var i = 0; i <= segments; i++) {
    var th = ta + (2 * Math.PI - 2 * ta) * i / segments;
    ring.push(R * Math.cos(th), R * Math.sin(th));
  }
  ring.push(D, 0);
  return ring;
}

/** A square ring, the shape the stiffness table was measured on. */
function squareRing(side, perEdge) {
  var corners = [[0, 0], [side, 0], [side, side], [0, side]], out = [];
  for (var e = 0; e < 4; e++) {
    for (var t = 0; t < perEdge; t++) {
      var u = t / perEdge, a = corners[e], b = corners[(e + 1) % 4];
      out.push(a[0] + (b[0] - a[0]) * u, a[1] + (b[1] - a[1]) * u);
    }
  }
  return out;
}

/**
 * A "C" - an annulus with a wedge removed, its mouth `open` radians wide.
 *
 * The shape that would disprove the brace rule if a brace ever spanned a gap: weld the mouth
 * shut and a C becomes an O, which is worse than the bug being fixed.
 */
function cShape(outerR, innerR, open, segments) {
  var ring = [], span = 2 * Math.PI - 2 * open, i;
  for (i = 0; i <= segments; i++) {
    var a = open + span * i / segments;
    ring.push(outerR * Math.cos(a), outerR * Math.sin(a));
  }
  for (i = segments; i >= 0; i--) {
    var b = open + span * i / segments;
    ring.push(innerR * Math.cos(b), innerR * Math.sin(b));
  }
  return ring;
}

